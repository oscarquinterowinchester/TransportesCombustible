package com.appchoferes.nomina.models.durandb.dtos;

public class Traslado {
    private String Base;
    private String Impuesto;
    private String TipoFactor;
    private String TasaOCuota;
    private String Importe;
    // Getters y setters

    /**
     * @return String return the Base
     */
    public String getBase() {
        return Base;
    }

    /**
     * @param Base the Base to set
     */
    public void setBase(String Base) {
        this.Base = Base;
    }

    /**
     * @return String return the Impuesto
     */
    public String getImpuesto() {
        return Impuesto;
    }

    /**
     * @param Impuesto the Impuesto to set
     */
    public void setImpuesto(String Impuesto) {
        this.Impuesto = Impuesto;
    }

    /**
     * @return String return the TipoFactor
     */
    public String getTipoFactor() {
        return TipoFactor;
    }

    /**
     * @param TipoFactor the TipoFactor to set
     */
    public void setTipoFactor(String TipoFactor) {
        this.TipoFactor = TipoFactor;
    }

    /**
     * @return String return the TasaOCuota
     */
    public String getTasaOCuota() {
        return TasaOCuota;
    }

    /**
     * @param TasaOCuota the TasaOCuota to set
     */
    public void setTasaOCuota(String TasaOCuota) {
        this.TasaOCuota = TasaOCuota;
    }

    /**
     * @return String return the Importe
     */
    public String getImporte() {
        return Importe;
    }

    /**
     * @param Importe the Importe to set
     */
    public void setImporte(String Importe) {
        this.Importe = Importe;
    }

}
